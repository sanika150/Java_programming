class datatype
{
	public static void main(String A[])
	{

		int a = 10;
		char ch ='S';
		float f = 21.5f;
		double d = 23.4556;
	
		System.out.println("value of integer is :"+a);

		System.out.println("value of character is :"+ch);

		System.out.println("value of float is :"+f);

		System.out.println("value of double is :"+d);

	}
}